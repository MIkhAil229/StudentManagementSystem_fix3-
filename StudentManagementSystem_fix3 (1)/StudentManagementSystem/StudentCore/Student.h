// проект решения (лежит в отдельном "общем" месте, чтобы не дублировать
// структуру в трёх проектах).

#pragma once

// Количество предметов, по которым выставляются оценки каждому студенту.
#define SUBJECTS_COUNT 5

// Максимальная длина ФИО (включая завершающий нулевой символ).
#define FULLNAME_LEN 100

struct Student
{
    int    id;                       // уникальный номер (1...N)
    char   fullName[FULLNAME_LEN];   // ФИО
    int    scores[SUBJECTS_COUNT];   // оценки по 5 предметам (2-5)
    double averageScore;             // средний балл
};
